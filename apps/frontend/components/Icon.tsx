export function Icon({
  name,
  size = 20,
  stroke = 1.75,
  className,
  style,
}: {
  name: string;
  size?: number;
  stroke?: number;
  className?: string;
  style?: CSSProperties;
}) {
  const Cmp = ICONS[name];
  if (!Cmp) return null;
  return <Cmp size={size} strokeWidth={stroke} className={className} style={style} aria-hidden />;
}
